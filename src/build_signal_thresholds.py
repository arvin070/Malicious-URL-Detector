"""
Derive the "security signal" thresholds from the BENIGN training distribution.

WHY THIS EXISTS
---------------
A UI that says "unusually long URL" has to be able to answer "unusual compared
to what?". Hard-coding a number (`url_length > 75`) would be an invented
threshold dressed up as a finding -- exactly what the frontend brief forbids.

So every continuous signal fires at a PERCENTILE OF THE BENIGN CORPUS, and the
percentile travels with the threshold so the UI can state it:

    "longer than 95% of known-benign URLs in the training corpus"

That sentence is checkable. "Unusually long" on its own is not.

Binary characteristics (an IP literal for a host, an '@' in the URL, punycode)
need no threshold -- they are present or absent -- so they are not listed here;
`webapp/assessment.py` reports those directly.

The percentiles come from the benign rows only. Using the whole corpus would
blunt them: half of it is phishing, so the "typical" value would already be
shifted toward what we are trying to flag.

SAFETY: reads the corpus as strings. Nothing is fetched or resolved.

Usage:
    python src/build_signal_thresholds.py
    python src/build_signal_thresholds.py --percentile 99
"""

import argparse
import json
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from features import extract_features, FEATURE_NAMES  # noqa: E402
from leakage import drop_exact_duplicates  # noqa: E402

# Continuous features that a non-specialist can actually interpret. The model
# uses all 122; these are only the ones worth SHOWING as a plain-language
# signal. Each is "higher = more unusual".
SIGNAL_FEATURES = [
    "url_length",
    "host_length",
    "path_length",
    "query_length",
    "num_dots",
    "num_hyphens",
    "num_special_chars",
    "num_digits",
    "subdomain_depth",
    "path_depth",
    "num_query_params",
    "num_percent_encoded",
    "suspicious_word_count",
    "host_entropy",
    "domain_max_consonant_run",
    "longest_subdomain_length",
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="data/real_urls.csv")
    ap.add_argument("--hard-negatives", default="data/hard_negatives.csv")
    ap.add_argument("--out", default="models/signal_thresholds.json")
    ap.add_argument("--percentile", type=float, default=95.0,
                    help="a signal fires above this percentile of BENIGN URLs")
    args = ap.parse_args()

    frames = [pd.read_csv(args.data).dropna(subset=["url", "label"])]
    if os.path.exists(args.hard_negatives):
        hn = pd.read_csv(args.hard_negatives).dropna(subset=["url"])
        hn["label"] = hn["label"].astype(int)
        frames.append(hn)
    df = pd.concat(frames, ignore_index=True)
    df["label"] = df["label"].astype(int)
    df["url"] = df["url"].astype(str)
    df, dup = drop_exact_duplicates(df)

    benign = df[df["label"] == 0]
    phish = df[df["label"] == 1]
    print("=" * 70)
    print("SIGNAL THRESHOLDS FROM THE BENIGN DISTRIBUTION")
    print("=" * 70)
    print(f"  corpus      {len(df):,} rows "
          f"({dup['canonical_duplicates_removed']:,} canonical duplicates removed)")
    print(f"  benign      {len(benign):,}   phishing {len(phish):,}")
    print(f"  percentile  p{args.percentile:g} of BENIGN")

    Xb = pd.DataFrame([extract_features(u) for u in benign["url"]],
                      columns=FEATURE_NAMES)
    Xp = pd.DataFrame([extract_features(u) for u in phish["url"]],
                      columns=FEATURE_NAMES)

    thresholds = {}
    print(f"\n  {'feature':<26}{'benign p50':>11}{'threshold':>11}"
          f"{'benign>':>9}{'phish>':>9}{'lift':>7}")
    for f in SIGNAL_FEATURES:
        if f not in Xb.columns:
            print(f"  {f:<26} MISSING from extractor -- skipped")
            continue
        b = Xb[f].to_numpy(dtype=float)
        p = Xp[f].to_numpy(dtype=float)
        thr = float(np.percentile(b, args.percentile))
        b_rate = float((b > thr).mean())
        p_rate = float((p > thr).mean())
        # How much more often phishing exceeds this than benign does. Reported
        # so the UI can avoid showing signals that carry no information.
        lift = (p_rate / b_rate) if b_rate > 0 else float("inf")
        thresholds[f] = {
            "threshold": thr,
            "percentile": args.percentile,
            "benign_median": float(np.median(b)),
            "benign_exceed_rate": round(b_rate, 4),
            "phishing_exceed_rate": round(p_rate, 4),
            "lift": round(lift, 2) if np.isfinite(lift) else None,
        }
        print(f"  {f:<26}{np.median(b):>11.2f}{thr:>11.2f}"
              f"{b_rate:>9.2%}{p_rate:>9.2%}{lift:>7.2f}")

    payload = {
        "_comment": ("Generated by src/build_signal_thresholds.py. Each threshold "
                     "is a percentile of the BENIGN training distribution, so the "
                     "UI can state what a value is unusual RELATIVE TO. Do not "
                     "hand-edit: regenerate instead."),
        "percentile": args.percentile,
        "source": os.path.basename(args.data),
        "n_benign": int(len(benign)),
        "n_phishing": int(len(phish)),
        "features": thresholds,
    }
    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        json.dump(payload, fh, indent=2)
    print(f"\n  wrote {args.out}")

    weak = [f for f, v in thresholds.items()
            if v["lift"] is not None and v["lift"] < 1.2]
    if weak:
        print(f"\n  NOTE: these barely separate the classes (lift < 1.2) and are "
              f"reported\n        as observations only, never as risk signals: "
              f"{', '.join(weak)}")
    print("=" * 70)


if __name__ == "__main__":
    main()
