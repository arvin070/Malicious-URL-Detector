"""
Infrastructure relationships between domains.

WHAT THIS IS, AND WHAT IT IS NOT
--------------------------------
A real infrastructure graph is built from passive DNS, IP allocation, WHOIS
registrant data and certificate transparency. URLGuard has none of those: it
does no DNS resolution at scan time, holds no WHOIS data, and reads no CT logs.
Inventing nodes and edges from data that was never collected would make a
convincing picture of nothing.

So this module builds only the edges that are genuinely derivable from
artefacts already on disk, and labels each edge with how it was obtained:

  redirect       domain A redirected to domain B, observed during the page
                 fetches in data/urlguard_web_dataset.csv
  shared_structure     two pages have near-identical structural fingerprints
                 (SimHash over the tag sequence), so they were probably
                 generated by the same phishing kit
  shared_host    two domains appear as hosts for URLs in the same blocklist
                 snapshot, which suggests shared hosting rather than a
                 relationship between the owners
  same_ip        only present when the corpus contains IP-literal URLs; the
                 "domain" IS the address, so no resolution is implied

Everything else a graph could show -- registrant, nameserver, ASN, certificate
issuer -- is absent, and `missing_edge_types` says so explicitly rather than
leaving the omission to be inferred from an empty picture.

NOTHING HERE CONTACTS THE NETWORK. It reads files.
"""

import argparse
import json
import os
import sys
from collections import defaultdict

import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from kit_similarity import hamming, NEAR_DUPLICATE_DISTANCE  # noqa: E402
from leakage import registered_domain  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_WEB = os.path.join(ROOT, "data", "urlguard_web_dataset.csv")
DEFAULT_OUT = os.path.join(ROOT, "models", "infra_graph.json")

# Edge kinds a full infrastructure graph would carry and this one cannot.
MISSING_EDGE_TYPES = {
    "same_ip_resolved": "requires DNS resolution, which URLGuard does not do",
    "same_nameserver": "requires DNS resolution",
    "same_registrant": "requires WHOIS data, which is not collected",
    "same_asn": "requires IP-to-ASN mapping, which is not collected",
    "same_certificate": "requires certificate transparency logs, not collected",
}


def _redirect_edges(df):
    """Domain -> domain, observed in the recorded fetches."""
    edges = defaultdict(int)
    if "final_url" not in df.columns:
        return edges
    for src_url, dst_url in zip(df["url"], df["final_url"]):
        if not isinstance(dst_url, str) or not dst_url:
            continue
        a, b = registered_domain(str(src_url)), registered_domain(dst_url)
        if a and b and a != b:
            edges[(a, b)] += 1
    return edges


def _kit_clusters(df, max_pairs=400_000):
    """Group pages built from the same kit, as CLUSTERS rather than pairs.

    TWO CORRECTIONS ARE BUILT INTO THIS, BOTH FOUND BY LOOKING AT THE OUTPUT
    --------------------------------------------------------------------
    1. Pairwise edges were quadratic. One real cluster -- 157 Bradesco
       credential pages across different domains -- produced 12,246 edges by
       itself, and the graph reported 49,854 edges for 2,704 pages. Clusters
       are emitted instead, so the graph stays linear in the corpus.

    2. Tag-structure similarity ALONE grouped unrelated legitimate sites.
       192.com, 33across.com and 3m.com landed in one "kit" because each
       served a near-empty page: 58 characters of text and no form at all.
       Structurally identical, related in no way whatsoever.

    Pages are therefore bucketed by the hash of their FORM SKELETON as well,
    and pages with no form at all are excluded rather than clustered on
    emptiness. That removed the empty-page clusters.

    3. The remaining clusters are NOT all phishing kits, and calling them
       that would be the same error one level up. Requiring a password field
       was the obvious next filter and is wrong: the largest real cluster --
       186 domains, 198 malicious pages against 2 benign -- has no password
       input in its served HTML at all, because the credential form is
       injected later. That filter would have deleted the one true finding
       and kept the search boxes.

    So this reports what it can actually establish: groups of distinct
    domains serving near-identical page structure. Each cluster carries the
    observed label composition of its pages as an ATTRIBUTE, so a reader can
    see that one cluster is 198 malicious to 2 benign and another is 80
    benign to 14 malicious. The clustering itself uses no labels; naming a
    cluster "a phishing kit" is a judgement left to the reader with the
    evidence in front of them.
    """
    if "tag_simhash" not in df.columns or "form_sha" not in df.columns:
        return [], 0

    labels = (df["label"].tolist() if "label" in df.columns
              else [None] * len(df))
    rows = []
    for u, h, fs, lab in zip(df["url"], df["tag_simhash"], df["form_sha"],
                             labels):
        dom = registered_domain(str(u))
        # A missing form_sha means the page had no form. Excluded: there is
        # nothing kit-like about two pages that both lack a login form.
        if pd.isna(h) or pd.isna(fs) or not str(fs).strip() or not dom:
            continue
        rows.append((dom, int(h), str(fs), lab))

    parent = list(range(len(rows)))

    def find(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i

    def union(i, j):
        a, b = find(i), find(j)
        if a != b:
            parent[b] = a

    # Bucket by form skeleton: same form AND near-identical tag structure.
    buckets = defaultdict(list)
    for idx, (_, _, fs, _l) in enumerate(rows):
        buckets[fs].append(idx)

    compared = 0
    truncated = False
    for group in buckets.values():
        for i in range(len(group)):
            for j in range(i + 1, len(group)):
                compared += 1
                if compared > max_pairs:
                    truncated = True
                    break
                if hamming(rows[group[i]][1], rows[group[j]][1]) <= NEAR_DUPLICATE_DISTANCE:
                    union(group[i], group[j])
            if truncated:
                break
        if truncated:
            break

    members = defaultdict(set)
    composition = defaultdict(lambda: {"malicious": 0, "benign": 0})
    for idx, (dom, _, _, lab) in enumerate(rows):
        root = find(idx)
        members[root].add(dom)
        if lab == 1:
            composition[root]["malicious"] += 1
        elif lab == 0:
            composition[root]["benign"] += 1

    clusters = []
    for root, doms in members.items():
        # One domain is a page, not a shared kit. Two or more DISTINCT
        # domains serving the same form and structure is the finding.
        if len(doms) < 2:
            continue
        comp = composition[root]
        clusters.append({
            "id": f"struct:{rows[root][2][:8]}",
            "domains": sorted(doms),
            "size": len(doms),
            "form_fingerprint": rows[root][2],
            # Observed in this corpus. Not a claim about the cluster.
            "pages_malicious": comp["malicious"],
            "pages_benign": comp["benign"],
        })
    clusters.sort(key=lambda c: -c["size"])
    return clusters, compared


def _shared_host_edges(df, min_cluster=2, max_cluster=40):
    """Domains hosting URLs that share a final hostname.

    Capped: a cluster of hundreds is a hosting provider, and connecting every
    pair inside it would assert a relationship between unrelated customers.
    """
    edges = defaultdict(int)
    if "final_url" not in df.columns:
        return edges
    from urllib.parse import urlsplit
    by_host = defaultdict(set)
    for u, f in zip(df["url"], df["final_url"]):
        if not isinstance(f, str):
            continue
        try:
            host = (urlsplit(f).hostname or "").lower()
        except ValueError:
            continue
        d = registered_domain(str(u))
        if host and d:
            by_host[host].add(d)
    for host, doms in by_host.items():
        if not (min_cluster <= len(doms) <= max_cluster):
            continue
        ds = sorted(doms)
        for i in range(len(ds)):
            for j in range(i + 1, len(ds)):
                edges[(ds[i], ds[j])] += 1
    return edges


def build(web_path=DEFAULT_WEB):
    if not os.path.exists(web_path):
        return {"available": False,
                "reason": f"{os.path.relpath(web_path, ROOT)} does not exist; "
                          f"run src/build_web_dataset.py first"}
    df = pd.read_csv(web_path)

    kinds = {
        "redirect": _redirect_edges(df),
        "shared_host": _shared_host_edges(df),
    }
    kit_clusters, kit_compared = _kit_clusters(df)

    label_by_domain = {}
    if "label" in df.columns:
        for u, lab in zip(df["url"], df["label"]):
            d = registered_domain(str(u))
            if d:
                label_by_domain.setdefault(d, set()).add(int(lab))

    nodes, edges = {}, []
    for kind, es in kinds.items():
        for (a, b), weight in es.items():
            edges.append({"source": a, "target": b, "kind": kind,
                          "weight": int(weight)})
            for d in (a, b):
                if d not in nodes:
                    labs = label_by_domain.get(d, set())
                    nodes[d] = {
                        "domain": d,
                        "degree": 0,
                        # Observed label in the corpus, not a verdict about
                        # the domain today.
                        "corpus_label": ("malicious" if labs == {1}
                                         else "benign" if labs == {0}
                                         else "mixed" if labs else "unknown"),
                    }
    # Kit clusters join each member domain to a cluster node, so the graph
    # stays linear in the number of pages instead of quadratic in the size of
    # the largest kit.
    for c in kit_clusters:
        nodes[c["id"]] = {"domain": c["id"], "degree": 0,
                          "corpus_label": "structure_cluster",
                          "size": c["size"],
                          "pages_malicious": c["pages_malicious"],
                          "pages_benign": c["pages_benign"],
                          "form_fingerprint": c["form_fingerprint"]}
        for d in c["domains"]:
            edges.append({"source": d, "target": c["id"],
                          "kind": "shared_structure", "weight": 1})
            if d not in nodes:
                labs = label_by_domain.get(d, set())
                nodes[d] = {
                    "domain": d, "degree": 0,
                    "corpus_label": ("malicious" if labs == {1}
                                     else "benign" if labs == {0}
                                     else "mixed" if labs else "unknown"),
                }

    for e in edges:
        nodes[e["source"]]["degree"] += 1
        nodes[e["target"]]["degree"] += 1

    return {
        "available": True,
        "source": os.path.relpath(web_path, ROOT),
        "pages_examined": int(len(df)),
        "nodes": sorted(nodes.values(), key=lambda n: -n["degree"]),
        "edges": edges,
        "counts": {**{k: len(v) for k, v in kinds.items()},
                   "shared_structure": sum(c["size"] for c in kit_clusters)},
        "kit_clusters": kit_clusters[:200],
        "kit_cluster_count": len(kit_clusters),
        "kit_pairs_compared": kit_compared,
        "node_count": len(nodes),
        "edge_count": len(edges),
        "missing_edge_types": MISSING_EDGE_TYPES,
        "limitation": (
            "Built only from relationships observable in recorded page "
            "fetches and structural fingerprints. It carries no DNS, WHOIS, "
            "ASN or certificate data, so absence of an edge is not evidence "
            "that two domains are unrelated."),
    }


def neighbours(graph, domain, limit=25):
    """Edges touching one domain. Returns an empty result, not an error, for
    a domain the corpus never saw -- which is the common case."""
    if not graph.get("available"):
        return {"available": False, "reason": graph.get("reason")}
    d = registered_domain(domain)
    hits = [e for e in graph["edges"] if e["source"] == d or e["target"] == d]
    return {
        "available": True,
        "domain": d,
        "in_graph": bool(hits),
        "edges": hits[:limit],
        "note": ("This domain does not appear in the recorded fetch corpus, "
                 "which says nothing about it." if not hits else
                 "Relationships observed in the recorded fetch corpus only."),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--web", default=DEFAULT_WEB)
    ap.add_argument("--out", default=DEFAULT_OUT)
    a = ap.parse_args()

    g = build(a.web)
    print("=" * 74)
    print("INFRASTRUCTURE GRAPH")
    print("=" * 74)
    if not g.get("available"):
        print(f"  unavailable: {g['reason']}")
        return 1
    print(f"  pages examined   {g['pages_examined']:,}")
    print(f"  domains (nodes)  {g['node_count']:,}")
    print(f"  edges            {g['edge_count']:,}")
    for k, v in g["counts"].items():
        print(f"    {k:<14} {v:,}")
    if g["kit_cluster_count"]:
        print(f"\n  shared-structure clusters: {g['kit_cluster_count']:,} "
              f"(distinct domains serving near-identical pages)")
        print(f"    {'domains':>7}  {'pages mal/ben':>13}  example members")
        for c in g["kit_clusters"][:6]:
            comp = f"{c['pages_malicious']}/{c['pages_benign']}"
            print(f"    {c['size']:>7}  {comp:>13}  "
                  f"{', '.join(c['domains'][:3])}")
    print("\n  most connected domains:")
    for n in g["nodes"][:10]:
        print(f"    {n['degree']:>4}  {n['domain'][:46]:<46} {n['corpus_label']}")
    print("\n  edge types this graph does NOT have:")
    for k, why in g["missing_edge_types"].items():
        print(f"    {k:<20} {why}")
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w", encoding="utf-8") as fh:
        json.dump(g, fh, indent=1)
    print(f"\n  wrote {os.path.relpath(a.out, ROOT)}")
    print("=" * 74)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
